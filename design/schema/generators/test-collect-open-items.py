# ⛔ 반대 방향도 함께 잠근다. 「아직」을 부정 목록에 넣자는 안이 있었으나 실측 반례가
#    있다 — `W-05-08` 미결 2 는 진짜 종결인데 «남의 화면» 미결을 「아직 살아 있어」로
#    언급한다. 넣으면 그 행이 거꾸로 열림이 된다. 그 표본을 아래에 박아 둔다.
#
